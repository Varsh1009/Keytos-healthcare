"""
Build results/comparison.md from the metrics JSON files (no number in it is typed by hand).
Run:  python models/make_comparison.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
ROWS = [("baseline_4mm", "Baseline 4 mm CNN"), ("cnn_2mm", "CNN 2 mm"), ("cnn_2mm_flip", "CNN 2 mm + L-R flips"),
        ("sfcn_ft", "SFCN fine-tuned (UK Biobank pretrained)"), ("volume", "Volume model (nWBV, eTIV, sex)"),
        ("ensemble", "Ensemble (image models; used by the app)"), ("ensemble_with_volume", "Ensemble + volume model")]


def load(name: str) -> dict | None:
    f = RESULTS / f"metrics_{name}.json"
    return json.loads(f.read_text()) if f.exists() else None


def coverage(name: str) -> tuple[float | None, float | None]:
    """Interval coverage of CALIBRATED intervals: cal_<name> for single models (their raw pred_std is only the
    seed spread, not an error estimate); ensembles are calibrated already."""
    for n in ((name,) if name.startswith("ensemble") else (f"cal_{name}",)):
        m = load(n)
        if m and m.get("interval_coverage_95") is not None:
            return m["interval_coverage_95"], m["mean_interval_width"]
    return None, None


def row(name: str, label: str) -> str | None:
    m = load(name)
    if m is None:
        return None
    cv, tr = m["clinical_validity"], m["test_retest"]
    cov, width = coverage(name)
    cov_s = f"{cov:.3f} (mean width {width:.1f} yrs)" if cov is not None else "n/a"
    return (f"| {label} | {m['mae']:.2f} | {m['r']:.3f} | {cv['auc']:.3f} ({cv['auc_ci'][0]:.2f}–{cv['auc_ci'][1]:.2f}) | "
            f"{tr['icc_3_1']:.3f} | ±{tr['smallest_detectable_change']:.2f} | {cov_s} |")


def summary() -> list[str]:
    base = load("baseline_4mm")
    out = []
    ms = {n: load(n) for n, _ in ROWS if load(n)}
    best = min(ms, key=lambda n: ms[n]["mae"])
    b, bm = base["test_retest"]["smallest_detectable_change"], ms[best]
    delta = base["mae"] - bm["mae"]
    out.append(f"- **Accuracy:** the lowest error is **{dict(ROWS)[best]}** at MAE {bm['mae']:.2f} years, "
               + (f"{delta:.2f} years better than the baseline's {base['mae']:.2f}." if delta > 0.05 else
                  f"no real improvement over the baseline's {base['mae']:.2f}."))
    for n in ("cnn_2mm", "sfcn_ft"):
        if n in ms:
            d = base["mae"] - ms[n]["mae"]
            out.append(f"- **{dict(ROWS)[n]}:** MAE {ms[n]['mae']:.2f} ({'better' if d > 0.05 else 'worse' if d < -0.05 else 'no change'}"
                       f" by {abs(d):.2f} years vs baseline); dementia AUC {ms[n]['clinical_validity']['auc']:.3f} vs "
                       f"{base['clinical_validity']['auc']:.3f}.")
    sdcs = {n: m["test_retest"]["smallest_detectable_change"] for n, m in ms.items()}
    bs = min(sdcs, key=sdcs.get)
    out.append(f"- **Reliability:** smallest detectable change ranges ±{min(sdcs.values()):.2f} to ±{max(sdcs.values()):.2f} years "
               f"(baseline ±{b:.2f}; best {dict(ROWS)[bs]}). All repeat scans are from 20 people aged 19–34, so this "
               "says nothing about reliability in older adults.")
    e = ms.get("ensemble")
    if e and e.get("interval_coverage_95") is not None:
        out.append(f"- **Intervals:** the ensemble's 95% intervals cover the true age of {e['interval_coverage_95']:.1%} of "
                   f"cognitively normal people (target 95%), mean width {e['mean_interval_width']:.1f} years. "
                   f"Interval scale factor fitted on training folds: {e['scale_factor_all_normal']:.2f}.")
        cc = e.get("confidence_counts_normal", {})
        mc = e.get("mae_by_confidence_normal", {})
        out.append("- **Confidence labels** (cognitively normal people): " + ", ".join(
            f"{c} {cc[c]} (MAE {mc[c]:.2f})" for c in ("high", "medium", "low") if c in cc) + ".")
    return out


def main() -> None:
    lines = ["# Brain-age model comparison", "",
             "Generated by `models/make_comparison.py` from `results/metrics_*.json`; every number comes from a script run.",
             "All models use the same subject-level, age-stratified 5 folds (`results/splits.json`), train only on "
             "cognitively normal first sessions, and every scan is scored only by models that never saw that person.", "",
             "| Model | MAE (yrs) | r | Dementia AUC (95% CI) | ICC(3,1) | Smallest detectable change (yrs) | 95% interval coverage |",
             "|---|---|---|---|---|---|---|"]
    lines += [r for n, lbl in ROWS if (r := row(n, lbl))]
    lines += ["", "MAE and r: cognitively normal people (out-of-fold). AUC: bias-corrected gap, dementia (CDR ≥ 0.5) vs "
              "normals at least as old as the youngest dementia participant, 1,000 bootstrap resamples. ICC and smallest "
              "detectable change: 20 real repeat scans. Coverage for single models uses their calibrated intervals "
              "(`cal_<model>`: residual SD by predicted-age band, scale fitted on training folds).", "",
              "## What improved and what did not", ""] + summary()
    chk = RESULTS / "sfcn_pretrained_check.json"
    if chk.exists():
        c = json.loads(chk.read_text())
        lines += ["", "## SFCN before fine-tuning (zero-shot check)", "",
                  f"The untouched UK Biobank SFCN on our upsampled scans: MAE {c['mae_44_80']:.2f} years and r = {c['r_44_80']:.2f} "
                  f"for the {c['n_44_80']} normal people aged 44–80 (its training range); predictions spanned only "
                  f"{c['pred_range'][0]:.0f}–{c['pred_range'][1]:.0f} years across ages 18–94. The correlation shows the "
                  "preprocessing (orientation, intensity) is right; the compressed range shows the domain shift "
                  "(different scanner, 2 mm scans upsampled to 1 mm) that fine-tuning has to fix. Upsampling adds no detail."]
    cfgf = RESULTS / "ensemble_config.json"
    if cfgf.exists():
        cfg = json.loads(cfgf.read_text())
        r = cfg["rules"]
        lines += ["", "## Confidence label rules (frozen)", "",
                  f"- **High:** 95% interval narrower than {r['high_width']} years, models agree within {r['max_disagreement']:.0f} years, "
                  f"template similarity ≥ {cfg['similarity_comfort_p5']:.2f} (5th percentile of training scans), age within "
                  f"{cfg['age_range'][0]:.0f}–{cfg['age_range'][1]:.0f}.",
                  f"- **Medium:** interval {r['high_width']}–{r['low_width']} years, or similarity between the upload cutoff "
                  f"{cfg['similarity_cutoff']:.2f} and {cfg['similarity_comfort_p5']:.2f}.",
                  f"- **Low:** interval wider than {r['low_width']} years, models disagree by more than {r['max_disagreement']:.0f} years, "
                  "age outside the training range, or similarity below the cutoff.",
                  f"- How the cutoffs were set: {r['how']}."]
    lines += ["", "## Deviations from the task spec (on purpose)", "",
              "- Models are ensembled on **raw** predictions, not bias-corrected ones: bias-corrected brain age uses the "
              "person's real age and would make MAE look better than it is. The bias correction is applied to the gap "
              "afterwards, for every model in the same way.",
              "- Bias-correction lines are fitted, for each fold, on the other folds' out-of-fold predictions "
              "(in-sample training predictions are overfit and would give the wrong line).",
              "- Residual SD for the interval is looked up by **predicted**-age band, so an upload needs no age.",
              "- The app ensemble uses image models only: the volume model needs OASIS's nWBV/eTIV, which an upload doesn't have.",
              "- Left-right flips were off for the new models (spec); the baseline keeps its original flip augmentation.",
              "", "## Limits", "",
              "- Small training set: 316 cognitively normal people, one dataset (OASIS-1), one scanner type.",
              "- Scans must be preprocessed like the training scans (skull-stripped, N4, FSL MNI152 2 mm).",
              "- Test-retest reliability comes from 20 young adults only.",
              "- A research tool, not a diagnosis."]
    (RESULTS / "comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
